"""
MirageSSH - Google Gemini AI Responder Client
Calls the Gemini API (e.g. gemini-1.5-flash) to generate authentic terminal
outputs for complex or unknown commands executed in the honeypot.
Uses standard urllib for zero mandatory external dependencies.
"""

from __future__ import annotations
import json
import logging
import os
import urllib.request
import urllib.error
from typing import Optional

from miragessh.ai.prompts import build_system_prompt

logger = logging.getLogger("miragessh.ai.gemini")


class GeminiClient:
    """Client for Google Gemini API."""

    def __init__(
        self,
        api_key: Optional[str] = None,
        model: str = "gemini-1.5-flash",
        temperature: float = 0.2,
        max_tokens: int = 1024,
        timeout: float = 4.0,
    ):
        self.api_key = api_key or os.getenv("GEMINI_API_KEY", "")
        self.model = model
        self.temperature = temperature
        self.max_tokens = max_tokens
        self.timeout = timeout

    @property
    def is_configured(self) -> bool:
        return bool(self.api_key and self.api_key.strip())

    def generate(
        self,
        command_line: str,
        user: str = "ubuntu",
        cwd: str = "/home/ubuntu",
        vfs_summary: str = "",
    ) -> Optional[str]:
        """
        Sends command context to Gemini API and returns simulated raw terminal output.
        """
        if not self.is_configured:
            logger.debug("Gemini API key not configured.")
            return None

        system_instruction = build_system_prompt(user=user, cwd=cwd, vfs_summary=vfs_summary)
        user_prompt = f"Command executed by {user} in {cwd}:\n{command_line}"

        endpoint = f"https://generativelanguage.googleapis.com/v1beta/models/{self.model}:generateContent?key={self.api_key}"

        payload = {
            "system_instruction": {
                "parts": [{"text": system_instruction}]
            },
            "contents": [
                {
                    "role": "user",
                    "parts": [{"text": user_prompt}]
                }
            ],
            "generationConfig": {
                "temperature": self.temperature,
                "maxOutputTokens": self.max_tokens,
            }
        }

        try:
            req_data = json.dumps(payload).encode("utf-8")
            req = urllib.request.Request(
                endpoint,
                data=req_data,
                headers={"Content-Type": "application/json"},
                method="POST",
            )
            with urllib.request.urlopen(req, timeout=self.timeout) as resp:
                resp_json = json.loads(resp.read().decode("utf-8"))

            candidates = resp_json.get("candidates", [])
            if not candidates:
                return None

            content_parts = candidates[0].get("content", {}).get("parts", [])
            if not content_parts:
                return None

            raw_text = content_parts[0].get("text", "")
            return self._sanitize_output(raw_text)

        except urllib.error.HTTPError as e:
            logger.warning(f"Gemini API HTTP error: {e.code} - {e.reason}")
            return None
        except Exception as e:
            logger.warning(f"Gemini API request failed: {e}")
            return None

    def _sanitize_output(self, text: str) -> str:
        """Removes accidental markdown code fences if generated by the LLM."""
        cleaned = text.strip()
        if cleaned.startswith("```"):
            lines = cleaned.splitlines()
            if lines[0].startswith("```"):
                lines = lines[1:]
            if lines and lines[-1].startswith("```"):
                lines = lines[:-1]
            cleaned = "\n".join(lines)
        if not cleaned.endswith("\n") and cleaned:
            cleaned += "\n"
        return cleaned
